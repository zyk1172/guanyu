export function normalizeUiLanguage(value) {
  return UI_LANGUAGE_OPTIONS.some((option) => option.value === value) ? value : 'zh-CN';
}

export function getUiText(language, key, fallback = key) {
  const locale = normalizeUiLanguage(language);
  if (locale === 'zh-CN' || locale === 'en-US') return UI_TEXT[locale][key] || fallback;
  return UI_TEXT_LOCALIZED[locale]?.[key] || UI_TEXT_HOME_FORM_LOCALIZED[locale]?.[key] || UI_TEXT['en-US'][key] || fallback;
}

export function formatUiText(template, values = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, key) => String(values[key] ?? `{${key}}`));
}
